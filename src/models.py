from typing import Any, Literal

from pydantic import BaseModel


class FunctionCallingPrompt(BaseModel):
    """Represent a natural-language request that needs a function call."""

    prompt: str


class FunctionParameter(BaseModel):
    """Describe the type of a parameter accepted by a function."""

    type: Literal[
        "string", "number", "integer", "boolean", "object", "array", "null"
    ]


class FunctionReturn(BaseModel):
    """Describe the type of result returned by a function."""

    type: Literal[
        "string", "number", "integer", "boolean", "object", "array", "null"
    ]


class FunctionDefinition(BaseModel):
    """Describe a function that the LLM can choose to call."""

    name: str
    description: str
    parameters: dict[str, FunctionParameter]
    returns: FunctionReturn

    model_config = {"extra": "forbid"}


class FunctionCall(BaseModel):
    """Represent the function call generated by the LLM."""

    prompt: str
    name: str
    parameters: dict[str, Any]

    model_config = {"extra": "forbid"}
